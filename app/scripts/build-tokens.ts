import { writeFileSync } from "node:fs";
import { primitiveNames, reducedMotion, themed } from "../tokens/index.ts";
import type { Value } from "../tokens/semantic.ts";

const line = (name: string, value: string) => `  --${name}: ${value};`;
const isToken = (v: string) => v in primitiveNames || v in themed;
const ref = (v: string) => (isToken(v) ? `var(--${v})` : v);
const value = (v: Value) =>
  typeof v === "string" ? ref(v) : `color-mix(in oklch, ${ref(v.mix)} ${v.amount}, transparent)`;

const theme = (mode: "dark" | "light") =>
  Object.entries(themed).map(([n, p]) => line(n, value(p[mode])));

const css = [
  "/* Generated by scripts/build-tokens.ts from tokens/. Do not edit. */",
  ":root {",
  "  color-scheme: light dark;",
  ...Object.entries(primitiveNames).map(([n, v]) => line(n, v)),
  "",
  ...theme("light"),
  "}",
  "",
  "@media (prefers-color-scheme: dark) {",
  "  :root {",
  ...theme("dark").map((l) => `  ${l}`),
  "  }",
  "}",
  "",
  "@media (prefers-reduced-motion: reduce) {",
  "  :root {",
  ...reducedMotion.map((n) => `  ${line(n, "0ms")}`),
  "  }",
  "}",
  "",
].join("\n");

writeFileSync(new URL("../tokens/design-tokens.css", import.meta.url), css);
console.log(
  `tokens.css: ${Object.keys(primitiveNames).length} primitive, ${Object.keys(themed).length} themed`,
);
