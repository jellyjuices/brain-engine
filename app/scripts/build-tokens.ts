import { writeFileSync } from "node:fs";
import { composed, primitiveNames, reducedMotion, shared, themed } from "../tokens/index.ts";
import type { Value } from "../tokens/semantic.ts";

const line = (name: string, value: string) => `  --${name}: ${value};`;
const ref = (name: string) => `var(--${name})`;
const value = (v: Value) =>
  typeof v === "string"
    ? ref(v)
    : `color-mix(in oklch, ${ref(v.mix)} ${ref(v.amount)}, transparent)`;

const primitiveBlock = Object.entries(primitiveNames).map(([n, v]) => line(n, v));
const sharedBlock = Object.entries(shared).map(([n, r]) => line(n, ref(r)));
const composedBlock = Object.entries(composed).map(([n, v]) => line(n, v));
const theme = (mode: "dark" | "light") =>
  Object.entries(themed).map(([n, p]) => line(n, value(p[mode])));

const css = [
  "/* Generated by scripts/build-tokens.ts from tokens/. Do not edit. */",
  ":root {",
  ...primitiveBlock,
  "",
  ...sharedBlock,
  ...composedBlock,
  "}",
  "",
  ':root, [data-theme="dark"] {',
  "  color-scheme: dark;",
  ...theme("dark"),
  "}",
  "",
  '[data-theme="light"] {',
  "  color-scheme: light;",
  ...theme("light"),
  "}",
  "",
  "@media (prefers-reduced-motion: reduce) {",
  "  :root {",
  ...reducedMotion.map((n) => `  ${line(n, ref("motion-duration-instant"))}`),
  "  }",
  "}",
  "",
].join("\n");

writeFileSync(new URL("../tokens/design-tokens.css", import.meta.url), css);
console.log(
  `tokens.css: ${Object.keys(primitiveNames).length} primitive, ${
    Object.keys(themed).length + Object.keys(shared).length + Object.keys(composed).length
  } semantic`,
);
